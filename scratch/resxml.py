"""
Compiled binary XML (res/xml) generator - aapt2-formatted accessibility service
configuration resource.

We cannot ADD a resource to resources.arsc (no resource-table surgery by design),
so the generated bytes shadow an EXISTING, UNREFERENCED res/xml resource inside
the APK: the file at the resource's zip path is replaced with this document while
its arsc entry (type id + entry id) stays intact. The platform resolves the
resource through arsc, gets our bytes, and compiles AccessibilityServiceInfo
from them.

The document is deliberately minimal:

    <accessibility-service xmlns:android="http://schemas.android.com/apk/res/android"
        android:canRetrieveWindowContent="true" />

Chunk layout follows AOSP ResourceTypes.h (same conventions as axml.py):
    file        magic 0x00080003, fileSize
    pool        0x0001  headerSize 0x1C
    map         0x0180  headerSize 0x08        attr-name idx -> framework attr id
    start ns    0x0100  headerSize 0x10
    start elem  0x0102  headerSize 0x10
    end elem    0x0103  headerSize 0x10
    end ns      0x0101  headerSize 0x10
    end doc     0x0105  headerSize 0x10

Only android:canRetrieveWindowContent sits in the config. It is the ONE thing a
runtime setServiceInfo() cannot grant (window-content capability is read from the
manifest config at enable time); every other setting (event types, flags,
feedback, timeout) is assigned at runtime in AdSkipAccessibilityService.
"""
import struct

TYPE_STRING_POOL = 0x0001
TYPE_NS_START = 0x0100
TYPE_NS_END = 0x0101
TYPE_ELEMENT_START = 0x0102
TYPE_ELEMENT_END = 0x0103
TYPE_END_DOC = 0x0105
TYPE_RES_MAP = 0x0180

ATTR_TYPE_STRING = 0x03
ATTR_TYPE_INT_BOOLEAN = 0x12
ATTR_TYPE_REFERENCE = 0x01  # (unused here, kept for symmetry)

ANDROID_NS = "http://schemas.android.com/apk/res/android"

# android.R.attr.canRetrieveWindowContent, verified against the android.jar
# R$attr constant pool (Xamarin Android.Resource.Attribute bindings set it to
# 16843653 = 0x01010385).
CAN_RETRIEVE_WINDOW_CONTENT = 0x01010385


def _utf8_len_prefix(n):
    """one-byte length for <0x80, two-byte form otherwise (aapt2 style)."""
    if n < 0x80:
        return bytes([n])
    return bytes([0x80 | ((n >> 8) & 0x7F), n & 0xFF])


def _string_pool(strings):
    """UTF-8 style ResStringPool chunk (flags 0x100), no styles."""
    n = len(strings)
    hdr = 28  # chunk header (8) + pool header (20)
    strings_start = hdr + 4 * n
    offsets = []
    body = bytearray()
    for s in strings:
        while len(body) % 4:
            body.append(0)
        offsets.append(len(body))
        enc = s.encode("utf-8")
        # [utf-16 char length][utf-8 byte length][bytes]
        body += _utf8_len_prefix(len(s)) + _utf8_len_prefix(len(enc)) + enc
    while len(body) % 4:
        body.append(0)
    chunk = bytearray()
    chunk += struct.pack(
        "<IIIIIII",
        (0x1C << 16) | TYPE_STRING_POOL, 0,        # header; chunkSize patched below
        n, 0,                                       # stringCount, styleCount
        0x100,                                      # flags: UTF-8
        strings_start,                              # stringsStart
        strings_start + len(body),                  # stylesStart
    )
    for o in offsets:
        chunk += struct.pack("<I", o)
    chunk += body
    struct.pack_into("<I", chunk, 4, len(chunk))
    return bytes(chunk)


def make_accessibility_config():
    """Compiled binary XML for <accessibility-service android:canRetrieveWindowContent="true"/>."""
    # string pool indices: [0]="android" [1]=uri [2]="accessibility-service" [3]="canRetrieveWindowContent"
    pool = _string_pool(["android", ANDROID_NS, "accessibility-service", "canRetrieveWindowContent"])

    # resource map: pool index 3 (the attr name) -> framework attr id 0x01010385
    map_chunk = (
        struct.pack("<II", (0x08 << 16) | TYPE_RES_MAP, 8 + 4 * 4)
        + struct.pack("<IIII", 0, 0, 0, CAN_RETRIEVE_WINDOW_CONTENT)
    )

    def ns_chunk(typ, prefix, uri):
        # node(16: header+line+comment) + nsExt(8: prefix,uri); headerSize 0x10
        return (struct.pack("<II", (0x10 << 16) | typ, 24)
                + struct.pack("<IIII", 0, 0xFFFFFFFF, prefix, uri))

    def elem_start(name, attrs):
        # node(16) + attrExt(16) + attrs; attributeStart relative to attrExt
        body = (
            struct.pack("<II", 0, 0xFFFFFFFF)  # lineNumber, comment=-1
            + struct.pack("<IIHHHHHH", 0xFFFFFFFF, name, 0x14, 0x14, len(attrs), 0, 0, 0)
            + b"".join(attrs)
        )
        return struct.pack("<II", (0x10 << 16) | TYPE_ELEMENT_START, 8 + len(body)) + body

    def elem_end(name):
        # node(16) + endElementExt(8: ns, name); headerSize 0x10
        return (struct.pack("<II", (0x10 << 16) | TYPE_ELEMENT_END, 24)
                + struct.pack("<IIII", 0, 0xFFFFFFFF, 0xFFFFFFFF, name))

    def end_doc():
        return struct.pack("<II", (0x10 << 16) | TYPE_END_DOC, 16) + struct.pack("<II", 0, 0xFFFFFFFF)

    def attr(ns, name, dtype, dval):
        tv = struct.pack("<HBB", 8, 0, dtype) + struct.pack("<I", dval)
        raw = dval if dtype == ATTR_TYPE_STRING else 0xFFFFFFFF
        return struct.pack("<III", ns, name, raw) + tv

    chunks = (
        pool
        + map_chunk
        + ns_chunk(TYPE_NS_START, 0, 1)
        + elem_start(2, [attr(1, 3, ATTR_TYPE_INT_BOOLEAN, 1)])
        + elem_end(2)
        + ns_chunk(TYPE_NS_END, 0, 1)
        + end_doc()
    )
    return struct.pack("<II", 0x00080003, 8 + len(chunks)) + chunks


def validate_config(data):
    """Structural validation mirroring axml.validate_manifest for the config:
    magic/size, 4-aligned covered chunk walk, balanced element + namespace tree,
    pool/r-map sanity, and the canRetrieveWindowContent mapping."""
    import axml

    magic, file_size = struct.unpack_from("<II", data, 0)
    assert magic == 0x00080003, "bad magic %08x" % magic
    assert file_size == len(data), "declared size %d != actual %d" % (file_size, len(data))

    chunks = axml.read_file(data)
    walked = 8 + sum(cs for (_t, _h, cs, _o) in chunks)
    assert walked == len(data), "chunk sizes sum to %#x but file is %#x" % (walked, len(data))

    stack = []
    ns_depth = 0
    pool = None
    map_entries = None
    for (ct, hs, cs, co) in chunks:
        assert ((hs | cs) & 0x3) == 0, "chunk 0x%04x @%#x not 4-byte aligned" % (ct, co)
        if ct == TYPE_STRING_POOL:
            pool = axml.parse_string_pool(data, co)
        elif ct == TYPE_RES_MAP:
            map_entries = list(struct.unpack_from("<%dI" % ((cs - 8) // 4), data, co + 8))
        elif ct == TYPE_ELEMENT_START:
            _ns, name = struct.unpack_from("<II", data, co + 16)
            stack.append(name)
        elif ct == TYPE_ELEMENT_END:
            _ens, name = struct.unpack_from("<II", data, co + 16)
            assert stack and stack[-1] == name, "unbalanced end element idx %d" % name
            stack.pop()
        elif ct == TYPE_NS_START:
            ns_depth += 1
        elif ct == TYPE_NS_END:
            ns_depth -= 1
        elif ct == TYPE_END_DOC:
            assert cs == 16 and hs == 0x10, "odd end-doc chunk (%#x/%#x)" % (hs, cs)
    assert not stack, "unclosed elements: %r" % stack
    assert ns_depth == 0, "unbalanced namespaces: %d" % ns_depth
    assert pool is not None and len(pool["strings"]) >= 4, "config pool wrong"
    assert pool["strings"][3] == "canRetrieveWindowContent", "attr name missing"
    assert map_entries is not None and len(map_entries) == len(pool["strings"]), "map/pool mismatch"
    assert map_entries[3] == CAN_RETRIEVE_WINDOW_CONTENT, "map entry 3 not %#x" % CAN_RETRIEVE_WINDOW_CONTENT
    return True


if __name__ == "__main__":
    import os
    out = os.path.join(os.path.dirname(os.path.abspath(__file__)), "a11y_config.xml.bin")
    blob = make_accessibility_config()
    validate_config(blob)
    with open(out, "wb") as f:
        f.write(blob)
    print("wrote %s (%d bytes), validate: OK" % (out, len(blob)))
    print("hex tail:", blob[-16:].hex(" "))